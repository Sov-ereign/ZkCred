// =============================================================================
// Witness Provider
// Creates the private witness callbacks that the Compact circuit calls
// to retrieve private data during proof generation.
// =============================================================================

export interface ZkCredWitnessInput {
  creditScore: number;
  annualIncome: bigint;
  age: number;
  userSalt: Uint8Array;
  adminKey?: Uint8Array;
  /** Prototype issuer key; this does not independently authenticate values. */
  issuerKey?: Uint8Array;
  /** Credential token = persistentHash([issuerKey, userSalt]) — generated by the issuer. */
  credentialToken?: Uint8Array;
}

export function createWitnessProvider(privateData: ZkCredWitnessInput) {
  return {
    getPrivateCreditScore: (): number => privateData.creditScore,
    getPrivateAnnualIncome: (): bigint => privateData.annualIncome,
    getPrivateAge: (): number => privateData.age,
    getPrivateSalt: (): Uint8Array => privateData.userSalt,
    getPrivateAdminKey: (): Uint8Array => privateData.adminKey ?? new Uint8Array(32),
    // Prototype issuer witnesses. They do not establish credential provenance.
    // A zeroed key/token will fail the on-chain issuerKeyHash assertion.
    getPrivateIssuerKey: (): Uint8Array => privateData.issuerKey ?? new Uint8Array(32),
    getPrivateCredentialToken: (): Uint8Array => privateData.credentialToken ?? new Uint8Array(32),
  };
}

// =============================================================================
// Cryptographic Utilities
// =============================================================================

export function generateSalt(): Uint8Array {
  if (typeof globalThis.crypto === "undefined" || typeof globalThis.crypto.getRandomValues !== "function") {
    throw new Error("Cryptographic randomness unavailable: globalThis.crypto.getRandomValues is required.");
  }
  const salt = new Uint8Array(32);
  globalThis.crypto.getRandomValues(salt);
  return salt;
}

export function saltToHex(salt: Uint8Array): string {
  return Array.from(salt)
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

