// =============================================================================
// Issuer Credential Utilities
// =============================================================================
//
// The on-chain circuit uses Compact's `persistentHash` primitive — NOT plain
// SHA-256 — for all credential commitments. The helpers below call the
// Compact-native `persistentHashVec1` / `persistentHashVec2` wrappers
// exported from `src/managed/index.ts` so that every value computed here is
// guaranteed to match what the circuit asserts.
//
// Scheme (matches zkcred.compact exactly):
//   issuerKeyHash   = persistentHash<Vector<1, Bytes<32>>>([issuerKey])
//   credentialToken = persistentHash<Vector<2, Bytes<32>>>([issuerKey, userSalt])
//
// The on-chain checks:
//   assert H([issuerKey])        == issuerKeyHash
//   assert H([issuerKey, salt])  == credentialToken
// These equalities do not bind score, income, or age to an issuer signature.

/**
 * Prototype token package. It is not an issuer-signed credential and does not
 * authenticate the user's score, income, or age.
 */
export interface IssuerCredential {
  /** The issuer's secret key (32 bytes). Keep this confidential. */
  issuerKey: Uint8Array;
  /** persistentHash([issuerKey, userSalt]) — the attestation token for this specific call. */
  credentialToken: Uint8Array;
  /** persistentHash([issuerKey]) — the public commitment stored on-chain. */
  issuerKeyHash: Uint8Array;
}

/**
 * Generates a new random issuer secret key.
 * The admin calls this once, then registers issuerKeyHash on-chain via initialize().
 */
export function generateIssuerKey(): Uint8Array {
  if (typeof globalThis.crypto === "undefined" || typeof globalThis.crypto.getRandomValues !== "function") {
    throw new Error("Cryptographic randomness unavailable: globalThis.crypto.getRandomValues is required.");
  }
  const key = new Uint8Array(32);
  globalThis.crypto.getRandomValues(key);
  return key;
}

/**
 * Computes the issuer key hash (on-chain commitment).
 *
 * Uses `persistentHash<Vector<1, Bytes<32>>>([issuerKey])` — the exact same
 * primitive as the Compact circuit — to guarantee the value matches on-chain.
 *
 * This is what the admin registers via initialize(issuerKeyHashParam).
 * Previously this used SHA-256, which will always fail the circuit assertion.
 */
export function computeIssuerKeyHash(issuerKey: Uint8Array): Uint8Array {
  const key32 = new Uint8Array(32);
  key32.set(issuerKey.slice(0, 32));
  return persistentHashVec1(key32);
}

/**
 * Generates the prototype issuer token for a user's salt. This does not
 * authenticate age, credit score, or income.
 *
 * credentialToken = persistentHash<Vector<2, Bytes<32>>>([issuerKey, userSalt])
 *
 * The Compact circuit verifies: persistentHash([issuerKey, salt]) == credentialToken.
 * Without the issuerKey, a user cannot forge a valid token.
 *
 * Previously this used SHA-256 over a concatenated buffer, which will always
 * fail the on-chain persistentHash assertion. Now uses the correct primitive.
 */
export function generateCredentialToken(
  issuerKey: Uint8Array,
  userSalt: Uint8Array,
): Uint8Array {
  const key32 = new Uint8Array(32);
  key32.set(issuerKey.slice(0, 32));
  const salt32 = new Uint8Array(32);
  salt32.set(userSalt.slice(0, 32));
  return persistentHashVec2(key32, salt32);
}

/**
 * Full prototype package: generates a public key hash and token together.
 * This is not a substitute for issuer-side credential verification/signing.
 *
 * Both values use persistentHash (not SHA-256) to match the on-chain circuit.
 * This function is now synchronous — no Promise required.
 */
export function issueCredential(
  issuerKey: Uint8Array,
  userSalt: Uint8Array,
): IssuerCredential {
  const issuerKeyHash = computeIssuerKeyHash(issuerKey);
  const credentialToken = generateCredentialToken(issuerKey, userSalt);
  return { issuerKey, credentialToken, issuerKeyHash };
}

